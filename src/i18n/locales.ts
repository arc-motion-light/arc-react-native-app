export type TranslationPlaceholderIssue = {
  locale: ArcLocale;
  key: TranslationKey;
  expected: string[];
  actual: string[];
};

const translationPlaceholders = (value: string): string[] =>
  Array.from(value.matchAll(/\{\{(\w+)\}\}/g), (match) => match[1]).sort();

export const validateTranslationPlaceholders = (): TranslationPlaceholderIssue[] => {
  const englishTable = translations.en as Record<TranslationKey, string>;
  const englishKeys = Object.keys(englishTable) as TranslationKey[];

  return (Object.keys(translations) as ArcLocale[])
    .filter((locale) => locale !== 'en')
    .flatMap((locale) => {
      const localeTable = translations[locale] as Record<TranslationKey, string>;
      return englishKeys.flatMap((key) => {
        const expected = translationPlaceholders(englishTable[key]);
        const actual = translationPlaceholders(localeTable[key]);
        return expected.join('\u0000') === actual.join('\u0000')
          ? []
          : [{ locale, key, expected, actual }];
      });
    });
};

export type TranslationParityIssue = {
  locale: ArcLocale;
  missing: string[];
  extra: string[];
};

export const validateTranslationParity = (): TranslationParityIssue[] => {
  const englishKeys = Object.keys(translations.en);
  const englishSet = new Set(englishKeys);

  return (Object.keys(translations) as ArcLocale[])
    .filter((locale) => locale !== 'en')
    .map((locale) => {
      const localeKeys = Object.keys(translations[locale]);
      const localeSet = new Set(localeKeys);
      return {
        locale,
        missing: englishKeys.filter((key) => !localeSet.has(key)),
        extra: localeKeys.filter((key) => !englishSet.has(key)),
      };
    })
    .filter((issue) => issue.missing.length > 0 || issue.extra.length > 0);
};
